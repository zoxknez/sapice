import {z} from "zod";
import {toolSchema} from "@/lib/catalog/taxonomy";

/**
 * Material library v2.
 *
 * Unlike the engineered thermal library (src/data/materials.ts, which stays the compiler input
 * for the 16 engineered models), this domain describes what a material can and cannot do in a
 * shelter. Thermal conductivity is optional: UNKNOWN is a valid and honest state.
 *
 * Qualitative properties (water resistance, durability, cutting difficulty...) are Šapice design
 * assumptions unless a source is attached to the thermal block or listed in sourceIds.
 */

const levelSchema = z.enum(["LOW", "MEDIUM", "HIGH"]);

export const materialCategorySchema = z.enum([
  "SHEET_WOOD",
  "SOLID_WOOD",
  "REUSED_WOOD",
  "RIGID_FOAM",
  "FIBROUS_INSULATION",
  "NATURAL_BOARD",
  "CONTAINER",
  "PAPER",
  "BEDDING_FILL",
  "FLOOR_SURFACE",
  "ROOF_COVERING",
  "MEMBRANE",
  "MASONRY",
  "CONSUMABLE",
  "HARDWARE",
  "SALVAGE"
]);

export const inventoryUnitSchema = z.enum(["SHEET", "PIECE", "LINEAR_M", "AREA_M2", "BALE", "PACK"]);

export const materialThermalSchema = z.discriminatedUnion("status", [
  z.object({
    status: z.literal("KNOWN"),
    lambdaPlanningWmK: z.number().positive(),
    lambdaRangeWmK: z.tuple([z.number().positive(), z.number().positive()]).nullable(),
    basis: z.enum(["GENERIC_PLANNING", "PRODUCT_DECLARED"]),
    sourceIds: z.array(z.string()).min(1)
  }),
  z.object({
    status: z.literal("UNKNOWN"),
    reasonSr: z.string(),
    reasonEn: z.string()
  }),
  z.object({
    status: z.literal("NOT_MODELLED"),
    reasonSr: z.string(),
    reasonEn: z.string()
  })
]);

export const libraryMaterialSchema = z.object({
  id: z.string(),
  nameSr: z.string(),
  nameEn: z.string(),
  category: materialCategorySchema,
  structuralRole: z.enum(["PRIMARY", "SECONDARY", "NONE"]),
  insulationRole: z.enum(["PRIMARY", "SECONDARY", "NONE"]),
  /** May the animal touch, chew or lie on it directly? */
  animalFacing: z.enum(["ALLOWED", "PROTECTED_ONLY", "NEVER"]),
  exteriorSuitability: z.enum(["SUITABLE", "PROTECTED", "UNSUITABLE"]),
  waterResistance: levelSchema,
  moistureSensitivity: levelSchema,
  thermal: materialThermalSchema,
  typicalThicknessesMm: z.array(z.number().positive()),
  /** Only when a supplier format is meaningful; always a planning value to verify locally. */
  planningStock: z
    .object({widthMm: z.number().positive(), heightMm: z.number().positive(), provenance: z.enum(["SOURCE", "ASSUMPTION"])})
    .nullable(),
  inventoryUnit: inventoryUnitSchema,
  cuttingDifficulty: z.enum(["NONE", "EASY", "MODERATE", "HARD"]),
  tools: z.array(toolSchema),
  durability: z.enum(["SHORT_TERM", "SEASONAL", "MULTI_YEAR"]),
  reusable: z.boolean(),
  reuseInspectionRequired: z.boolean(),
  edgeProtectionRequired: z.boolean(),
  coatingRequired: z.boolean(),
  limitationsSr: z.array(z.string()),
  limitationsEn: z.array(z.string()),
  sourceIds: z.array(z.string()),
  notesSr: z.string(),
  notesEn: z.string()
});

export type LibraryMaterial = z.infer<typeof libraryMaterialSchema>;
export type MaterialThermal = z.infer<typeof materialThermalSchema>;

const unknownThermal = (reasonSr: string, reasonEn: string): MaterialThermal => ({status: "UNKNOWN", reasonSr, reasonEn});
const notModelled = (reasonSr: string, reasonEn: string): MaterialThermal => ({status: "NOT_MODELLED", reasonSr, reasonEn});

/** R_IP per inch → λ in W/mK: λ = 0.0254 / (R_IP × 0.17611). Rounded to 4 decimals. */
export function lambdaFromRPerInch(rPerInch: number) {
  return Math.round((0.0254 / (rPerInch * 0.17611)) * 10000) / 10000;
}

