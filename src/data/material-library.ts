export const materialLibrary: Record<string, LibraryMaterial> = Object.fromEntries(
  raw.map((entry) => {
    const parsed = libraryMaterialSchema.parse({...defaults, ...entry});
    return [parsed.id, parsed];
  })
);

export function getLibraryMaterial(id: string) {
  const material = materialLibrary[id];
  if (!material) throw new Error(`Unknown library material: ${id}`);
  return material;
}

export function materialName(material: Pick<LibraryMaterial, "nameSr" | "nameEn">, locale: "sr" | "en") {
  return locale === "sr" ? material.nameSr : material.nameEn;
}
